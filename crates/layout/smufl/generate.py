#!/usr/bin/env python3
"""Writes crates/layout/src/glyphs/bravura.rs from Bravura's SMuFL metadata.

The metadata must match the font in crates/app/assets/fonts (Bravura 1.392):

    git clone https://github.com/steinbergmedia/bravura
    git -C bravura show 301087c:redist/bravura_metadata.json > bravura_metadata.json
    python3 crates/layout/smufl/generate.py bravura_metadata.json
    cargo fmt

Only the glyphs below are written, with their advance width, bounding box and
the stem anchors the layout uses, plus the engraving defaults.
"""

import json
import sys
from pathlib import Path

# (Rust name, SMuFL name, code point)
GLYPHS = [
    ("NOTEHEAD_BLACK", "noteheadBlack", 0xE0A4),
    ("NOTEHEAD_HALF", "noteheadHalf", 0xE0A3),
    ("NOTEHEAD_PAREN_LEFT", "noteheadParenthesisLeft", 0xE0F5),
    ("NOTEHEAD_PAREN_RIGHT", "noteheadParenthesisRight", 0xE0F6),
    ("AUGMENTATION_DOT", "augmentationDot", 0xE1E7),
    ("CLEF_PERCUSSION", "unpitchedPercussionClef1", 0xE069),
    ("FLAG_8TH_UP", "flag8thUp", 0xE240),
    ("FLAG_8TH_DOWN", "flag8thDown", 0xE241),
    ("FLAG_16TH_UP", "flag16thUp", 0xE242),
    ("FLAG_16TH_DOWN", "flag16thDown", 0xE243),
    ("FLAG_32ND_UP", "flag32ndUp", 0xE244),
    ("FLAG_32ND_DOWN", "flag32ndDown", 0xE245),
    ("ACCENT_ABOVE", "articAccentAbove", 0xE4A0),
    ("REST_WHOLE", "restWhole", 0xE4E3),
    ("REST_HALF", "restHalf", 0xE4E4),
    ("REST_QUARTER", "restQuarter", 0xE4E5),
    ("REST_8TH", "rest8th", 0xE4E6),
    ("REST_16TH", "rest16th", 0xE4E7),
    ("REST_32ND", "rest32nd", 0xE4E8),
]
GLYPHS += [(f"TIME_SIG_{d}", f"timeSig{d}", 0xE080 + d) for d in range(10)]
GLYPHS += [(f"TUPLET_{d}", f"tuplet{d}", 0xE880 + d) for d in range(10)]

ANCHORS = ["stemUpSE", "stemDownNW", "stemUpNW", "stemDownSW"]

DEFAULTS = ["beamThickness", "beamSpacing", "thinBarlineThickness"]


def snake(name):
    """stemUpSE -> STEM_UP_SE"""
    out = ""
    for i, c in enumerate(name):
        if c.isupper() and i > 0 and not name[i - 1].isupper():
            out += "_"
        out += c
    return out.upper()


def num(x):
    s = f"{x:.4f}".rstrip("0")
    s = s + "0" if s.endswith(".") else s
    return "0.0" if s == "-0.0" else s


def main():
    meta = json.loads(Path(sys.argv[1]).read_text())
    assert meta["fontVersion"] == 1.392, meta["fontVersion"]
    out = [
        "//! Bravura 1.392 metrics, in staff spaces with y up, from its SMuFL",
        "//! metadata. Generated by `crates/layout/smufl/generate.py`; do not edit.",
        "",
        "use super::Glyph;",
        "",
    ]
    for rust, name, cp in GLYPHS:
        bbox = meta["glyphBBoxes"][name]
        sw, ne = bbox["bBoxSW"], bbox["bBoxNE"]
        adv = meta["glyphAdvanceWidths"][name]
        out.append(
            f"pub const {rust}: Glyph = Glyph {{ ch: '\\u{{{cp:04X}}}', advance: {num(adv)}, "
            f"sw: [{num(sw[0])}, {num(sw[1])}], ne: [{num(ne[0])}, {num(ne[1])}] }};"
        )
    out += ["", "/// Stem attachment points, relative to the glyph's origin."]
    for rust, name, _ in GLYPHS:
        for anchor, (x, y) in meta["glyphsWithAnchors"].get(name, {}).items():
            if anchor in ANCHORS:
                out.append(f"pub const {rust}_{snake(anchor)}: [f32; 2] = [{num(x)}, {num(y)}];")
    out += ["", "/// Line thicknesses and spacings the font is designed for."]
    for key in DEFAULTS:
        out.append(f"pub const {snake(key)}: f32 = {num(meta['engravingDefaults'][key])};")
    target = Path(__file__).resolve().parent.parent / "src" / "glyphs" / "bravura.rs"
    target.write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
